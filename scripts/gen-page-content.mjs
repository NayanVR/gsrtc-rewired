#!/usr/bin/env node
// One-off: compiles scraped /tmp/gsrtc-content/*.json into src/data/page-content.ts
// Run: node scripts/gen-page-content.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "/tmp/gsrtc-content";
const OUT = "src/data/page-content.ts";

// Portal / external action links (no article content to scrape) — slug -> url.
const EXTERNAL_LINKS = {
	"agent-allotment":
		"https://gsrtc.in/OPRSOnline/preFranchiseeAgentTransaction.do",
	"cancel-ticket":
		"https://www.gsrtc.in/OPRSOnline/preTicketCancellation.do?hiddenAction=TicketCancel&flag=C",
	"e-top-status": "https://gsrtc.in/OPRSPhonepe/preGatewayTransactionStatus.do",
	"gsrtc-agent-login": "https://www.gsrtc.in/OPRSWeb/preUserAuthenticate.do",
	"gujarat-pavitra-yatradham-vikas-board": "https://yatradham.gujarat.gov.in/",
	"india-code": "https://indiacode.nic.in/",
	"new-agent-register":
		"https://gsrtc.in/OPRSOnline/jsp/franchiseeTerms&Conditions.jsp",
	"new-commuter-bus-pass":
		"https://www.gsrtc.in/OPRSPass/preOnlinePassengerNewBusPassSystem.do?hiddenAction=PassengerNewBussPass",
	"print-sms-ticket": "https://www.gsrtc.in/OPRSOnline/prePrintTicket.do",
	"refund-transaction-enquiry":
		"https://gsrtc.in/OPRSPhonepe/preGatewayTransactionStatus.do",
	"reschedule-my-journey":
		"https://gsrtc.in/OPRSOnline/prePonePostPoneTicket.do",
	"service-regulation":
		"https://drive.google.com/file/d/1e0cfVQIlze3gPkZ9slXhMwRG--8a6h52/view",
	"sharvan-tirth-darshan": "https://yatradham.gujarat.gov.in/Booking",
	"unity-booking": "https://www.soutickets.in/#/gsrtc-booking",
	"view-history": "https://www.gsrtc.in/OPRSOnline/preViewBookingHistoryNew.do",
	"waiting-list-ticket-status":
		"https://www.gsrtc.in/OPRSOnline/preWaitingListTicketStatus.do",
	"wallet-account": "https://gsrtc.in/OPRSOnline/preGsrtcWalletAccount.do",
	"wallet-passbook":
		"https://gsrtc.in/OPRSOnline/preGsrtcWalletAccountSummary.do",
};

const content = {};
for (const file of readdirSync(SRC).filter((f) => f.endsWith(".json"))) {
	const raw = JSON.parse(readFileSync(`${SRC}/${file}`, "utf8"));
	const slug = raw.slug ?? file.replace(/\.json$/, "");
	const entry = {};
	if (raw.intro) {
		entry.intro = raw.intro;
	}
	const sections = (raw.sections ?? []).filter(
		(s) => s && (s.heading || s.paragraphs?.length || s.bullets?.length)
	);
	if (sections.length) {
		entry.sections = sections;
	}
	if (raw.contact && Object.keys(raw.contact).length) {
		entry.contact = raw.contact;
	}
	content[slug] = entry;
}

const header = `// AUTO-GENERATED by scripts/gen-page-content.mjs — scraped from gsrtc.in.
// Edit the scraper output and re-run, not this file by hand.

export interface PageSection {
	heading?: string;
	paragraphs?: string[];
	bullets?: string[];
}

export interface PageContact {
	address?: string;
	phone?: string;
	email?: string;
}

export interface PageContent {
	intro?: string;
	sections?: PageSection[];
	contact?: PageContact;
}
`;

const body = `
export const PAGE_CONTENT: Record<string, PageContent> = ${JSON.stringify(content, null, "\t")};

export const EXTERNAL_LINKS: Record<string, string> = ${JSON.stringify(EXTERNAL_LINKS, null, "\t")};
`;

writeFileSync(OUT, header + body);
console.log(
	`Wrote ${OUT}: ${Object.keys(content).length} content pages, ${Object.keys(EXTERNAL_LINKS).length} external links`
);
